import AppKit

/// Inserts text into the frontmost app by briefly borrowing the clipboard
/// and synthesizing ⌘V, then restoring whatever was on the clipboard before.
enum TextInserter {
    @MainActor
    static func paste(_ text: String) {
        let pasteboard = NSPasteboard.general

        // Snapshot current clipboard contents (all types).
        let saved: [[NSPasteboard.PasteboardType: Data]] = (pasteboard.pasteboardItems ?? []).map { item in
            var entry: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { entry[type] = data }
            }
            return entry
        }

        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        markTransient(item)
        pasteboard.writeObjects([item])

        sendCmdV()

        // Restore the previous clipboard after the paste has landed.
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.8) {
            guard !saved.isEmpty else { return }
            pasteboard.clearContents()
            let items: [NSPasteboardItem] = saved.map { entry in
                let item = NSPasteboardItem()
                for (type, data) in entry { item.setData(data, forType: type) }
                markTransient(item)
                return item
            }
            pasteboard.writeObjects(items)
        }
    }

    /// Marks a clipboard item as temporary (nspasteboard.org convention) so
    /// clipboard history apps like Alfred, Raycast and Maccy skip it. Without
    /// this, every dictation and every clipboard restore lands in their history.
    private static func markTransient(_ item: NSPasteboardItem) {
        for marker in ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            item.setData(Data(), forType: NSPasteboard.PasteboardType(marker))
        }
    }

    private static func sendCmdV() {
        guard let source = CGEventSource(stateID: .combinedSessionState) else { return }
        let vKey: CGKeyCode = 9
        let keyDown = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true)
        let keyUp = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false)
        keyDown?.flags = .maskCommand
        keyUp?.flags = .maskCommand
        keyDown?.post(tap: .cghidEventTap)
        keyUp?.post(tap: .cghidEventTap)
    }
}
